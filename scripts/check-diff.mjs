import { chromium } from '/home/yan/dsh-src/node_modules/.pnpm/playwright-core@1.61.1/node_modules/playwright-core/index.mjs';
const BASE = process.argv[2] || 'http://127.0.0.1:8890';
const dir = encodeURIComponent('novel-《凡人问道》');
const b = await chromium.launch({ executablePath: '/home/yan/.cache/ms-playwright/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errs = [];
p.on('console', m => m.type() === 'error' && errs.push(m.text()));
p.on('pageerror', e => errs.push('pageerror: ' + e.message));
await p.goto(`${BASE}/#/b/${dir}/review/2`, { waitUntil: 'networkidle' });
await p.waitForTimeout(1500);
const diffs = await p.locator('.issue .diff').allInnerTexts();
const na = await p.locator('.not-applicable').allInnerTexts();
console.log('每条问题的 diff 数:', diffs.length);
console.log('不可自动改写提示:', na.length);
if (diffs[0]) console.log('第一段 diff:\n' + diffs[0].slice(0, 200));
if (na[0]) console.log('示例提示:', na[0].slice(0, 80));
// 点第一条可采纳的「采纳」再预览
const adoptBtn = p.locator('.issue button').filter({ hasText: /^(采纳|标记)$/ }).first();
await adoptBtn.click();
await p.waitForTimeout(300);
const previewBtn = p.getByRole('button', { name: '预览已采纳的改写' });
console.log('预览按钮可见:', await previewBtn.isVisible());
await previewBtn.click();
await p.waitForTimeout(1200);
const card = await p.locator('.diff-card pre').innerText().catch(() => '(无)');
console.log('预览卡片内容前 160:', card.slice(0, 160));
await p.screenshot({ path: 'docs/screenshots/03-review.png', fullPage: true });
console.log('errors:', errs.length ? errs : 'none');
await b.close();
